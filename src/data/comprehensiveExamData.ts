export function getComprehensiveQuiz(type: 'pre_test' | 'post_test'): Quiz {
  const isPre = type === 'pre_test';
  const raw = isPre ? COMPREHENSIVE_PRE_QUESTIONS : COMPREHENSIVE_POST_QUESTIONS;
  const mappedQuestions: QuizQuestion[] = raw.map((q, idx) => {
    const correctIdx = q.choices.findIndex((c) => c.isCorrect);
    return {
      id: q.id,
      question: q.prompt,
      options: q.choices.map((c) => c.text),
      correctIndex: correctIdx >= 0 ? correctIdx : 0,
      correctAnswer: correctIdx >= 0 ? correctIdx : 0,
      explanation: `${q.explanation}${q.textbookReference ? ` (${q.textbookReference})` : ''}`,
    };
  });

  return {
    id: `quiz-7-${isPre ? 'pre' : 'post'}`,
    chapterNumber: 7,
    title: isPre
      ? 'แบบทดสอบวัดผลสัมฤทธิ์ก่อนเรียน รวม 6 บท (Comprehensive Pre-test 30 ข้อ)'
      : 'แบบทดสอบวัดผลสัมฤทธิ์หลังเรียน รวม 6 บท (Comprehensive Post-test 30 ข้อ)',
    type: type,
    totalQuestions: 30,
    passThresholdPercent: 60,
    isEnabled: true,
    questions: mappedQuestions,
  };
}
